"""Compose the GitHub Release body from the CHANGELOG and the generated charts.

Kept as a script rather than inline shell in the workflow for the usual reason:
shell embedded in YAML cannot be tested. This can, and it is the piece most likely
to break quietly -- a release body that silently loses its changelog, or links to
charts that were never uploaded, is only noticed after publishing.

Usage::

    python scripts/release_notes.py \\
        --tag v0.1.0 \\
        --repository owner/repo \\
        --assets release-assets \\
        --output body.md
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

#: Charts to embed, in reading order, with their headings. Each must exist in the
#: assets directory or the release is refused -- a broken image on a Release page
#: is worse than no image.
CHARTS: tuple[tuple[str, str], ...] = (
    ("pass-heal.svg", "Pass@1 vs Heal@1"),
    ("radar.svg", "Dimension profile"),
    ("taxonomy.svg", "Error taxonomy"),
)

#: Charts are linked from the repository, *not* from the Release assets.
#:
#: This is not a style preference. GitHub serves Release assets with
#: ``Content-Type: application/octet-stream`` and ``Content-Disposition:
#: attachment``, so an ``![](release-asset-url)`` in a Release body renders as a
#: broken image -- the browser is told to download the file rather than display it.
#: Verified against the live release:
#:
#:   release asset          -> application/octet-stream, attachment  (broken)
#:   raw.githubusercontent  -> image/svg+xml, no disposition        (renders)
#:
#: Embedding from the tagged commit also means a Release page keeps showing the
#: charts that were current for that tag, rather than whatever the assets hold.
RAW_BASE = "https://raw.githubusercontent.com/{repository}/{tag}/docs/charts/{name}"

INSTALL_TEMPLATE = """\
## Install

```bash
pip install structbench
```

Or install this exact release directly from the assets below:

```bash
pip install https://github.com/{repository}/releases/download/{tag}/structbench-{version}-py3-none-any.whl
```

## Try it with no API key

```bash
structbench validate
structbench run -m mock:good,mock:flaky --charts charts
```
"""


def changelog_section(changelog: str, version: str) -> str | None:
    """Return the body of the ``## [version]`` section, or ``None``.

    Stops at the next ``## [`` heading so a release never advertises another
    version's changes.
    """
    pattern = re.compile(
        rf"^##\s*\[{re.escape(version)}\][^\n]*\n(.*?)(?=^##\s*\[|\Z)",
        re.MULTILINE | re.DOTALL,
    )
    match = pattern.search(changelog)
    if not match:
        return None
    body = match.group(1).strip()
    return body or None


def version_from_tag(tag: str) -> str:
    return tag.lstrip("v").strip()


def build_body(
    *,
    tag: str,
    repository: str,
    assets: Path,
    changelog_path: Path | None = None,
    require_charts: bool = True,
) -> str:
    """Compose the full Markdown body."""
    version = version_from_tag(tag)
    parts: list[str] = [INSTALL_TEMPLATE.format(repository=repository, tag=tag, version=version)]

    available = [(name, heading) for name, heading in CHARTS if (assets / name).is_file()]
    missing = [name for name, _ in CHARTS if not (assets / name).is_file()]
    if require_charts and missing:
        raise FileNotFoundError(
            f"missing chart asset(s) in {assets}: {', '.join(missing)}; "
            "the release body would link to images that do not exist"
        )

    if available:
        parts.append("## Charts from this release\n")
        parts.append(
            "<sub>Generated by the offline simulator on the full 86-case suite. "
            "These are simulated models, not real ones — see the README.</sub>\n"
        )
        for name, heading in available:
            # Linked from the tagged commit, not from the Release assets: GitHub
            # serves assets as attachments, which browsers download instead of
            # rendering, so an asset URL here would show a broken image.
            url = RAW_BASE.format(repository=repository, tag=tag, name=name)
            parts.append(f"### {heading}\n")
            parts.append(f"![{heading}]({url})\n")

    leaderboard = assets / "leaderboard.md"
    if leaderboard.is_file():
        parts.append("## Leaderboard\n")
        parts.append(leaderboard.read_text(encoding="utf-8").strip() + "\n")

    path = changelog_path or (ROOT / "CHANGELOG.md")
    section = None
    if path.is_file():
        section = changelog_section(path.read_text(encoding="utf-8"), version)

    parts.append("## What changed\n")
    if section:
        parts.append(section + "\n")
    else:
        parts.append(
            f"No `[{version}]` section found in `CHANGELOG.md`; "
            "see that file for the full history.\n"
        )

    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tag", required=True, help="Release tag, e.g. v0.1.0.")
    parser.add_argument("--repository", required=True, help="owner/repo.")
    parser.add_argument("--assets", default="release-assets", help="Directory of release assets.")
    parser.add_argument("--changelog", default=None, help="Path to CHANGELOG.md.")
    parser.add_argument("--output", default=None, help="Write here instead of stdout.")
    parser.add_argument(
        "--allow-missing-charts",
        action="store_true",
        help="Do not fail when a chart asset is absent (used for local previews).",
    )
    args = parser.parse_args(argv)

    try:
        body = build_body(
            tag=args.tag,
            repository=args.repository,
            assets=Path(args.assets),
            changelog_path=Path(args.changelog) if args.changelog else None,
            require_charts=not args.allow_missing_charts,
        )
    except FileNotFoundError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    if args.output:
        Path(args.output).write_text(body, encoding="utf-8")
        print(f"wrote {args.output} ({len(body):,} chars)", file=sys.stderr)
    else:
        print(body)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
